import {chromium} from '@playwright/test';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1536,height:960}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
  await page.goto('http://127.0.0.1:5174/',{waitUntil:'networkidle'});
  const point=await page.evaluate(()=>{const d=__roomDebug,c=d.scene.getObjectByName('Couch_portal'),p=c.localToWorld(c.position.clone().set(0,.87,.1)).project(d.camera);return{x:(p.x*.5+.5)*innerWidth,y:(-p.y*.5+.5)*innerHeight};});
  await page.mouse.move(point.x,point.y);await page.waitForTimeout(350);
  const peek=await page.evaluate(()=>({angle:__roomDebug.couchPortal.lid.rotation.x,visible:__roomDebug.couchPortal.portal.visible,active:__roomDebug.couchPortal.active}));
  if(peek.angle>-.2||peek.angle<-.3||!peek.visible||peek.active)throw Error('Physical hover did not reveal a small portal preview');
  await page.screenshot({path:'qa/couch-hover-preview.png'});
  await page.mouse.move(10,10);await page.waitForTimeout(350);
  if(await page.evaluate(()=>__roomDebug.couchPortal.lid.rotation.x!==0||__roomDebug.couchPortal.portal.visible))throw Error('Pointer leave did not close preview');
  await page.locator('#contact-label').focus();
  if(await page.evaluate(()=>__roomDebug.couchPortal.lid.rotation.x>-.2))throw Error('Keyboard focus hint missing');
  await page.locator('#contact-label').evaluate(el=>el.blur());
  await page.mouse.move(point.x,point.y);await page.waitForTimeout(350);
  await page.mouse.click(point.x,point.y);
  if(await page.evaluate(()=>__roomDebug.couchPortal.lid.rotation.x>-.2))throw Error('Click snapped preview shut');
  await page.waitForTimeout(1200);
  if(await page.evaluate(()=>__roomDebug.couchPortal.lid.rotation.x> -1))throw Error('Full opening did not continue');
  await page.locator('.portal-skip').click();await page.keyboard.press('Escape');await page.waitForTimeout(1100);
  await page.locator('#contact-label').evaluate(el=>el.blur());await page.mouse.move(10,10);await page.waitForTimeout(350);
  await page.mouse.move(point.x,point.y);await page.waitForTimeout(350);
  if(await page.evaluate(()=>!__roomDebug.couchPortal.lining.parent.visible))throw Error('Return left preview tunnel hidden');
  await page.mouse.move(10,10);await page.waitForTimeout(350);
  await page.emulateMedia({reducedMotion:'reduce'});await page.mouse.move(point.x,point.y);
  await page.waitForTimeout(80);
  if(await page.evaluate(()=>__roomDebug.couchPortal.lid.rotation.x!==-.24))throw Error('Reduced motion hint must be static');
  if(errors.length)throw Error(errors.join('\n'));
  console.log('PASS couch hover, leave, focus, continuous click, return and reduced motion');
}finally{await browser.close();}
