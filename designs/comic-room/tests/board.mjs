import {chromium} from '@playwright/test';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1536,height:960}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5174/',{waitUntil:'networkidle'});
await page.locator('#about-label').click();await page.locator('#board-view').waitFor({state:'visible'});
if(await page.locator('#panel').evaluate(el=>el.open))throw Error('Board opened a dialog');
if(!await page.evaluate(()=>__roomDebug.boardView.active))throw Error('Board did not activate');
await page.screenshot({path:'qa/corkboard-whole.png'});
await page.setViewportSize({width:1200,height:800});await page.waitForTimeout(100);
if(!await page.locator('.board-exit').isVisible())throw Error('Resize lost exit');
await page.locator('.board-exit').click();await page.waitForTimeout(1000);
if(!await page.locator('#about-label').evaluate(el=>el===document.activeElement))throw Error('Board focus not restored');
await page.emulateMedia({reducedMotion:'reduce'});
await page.locator('.room-map summary').click();await page.getByRole('button',{name:'About ↗',exact:true}).click();await page.locator('#board-view').waitFor({state:'visible'});
await page.keyboard.press('Escape');await page.waitForTimeout(100);
if(!await page.locator('.room-map summary').evaluate(el=>el===document.activeElement))throw Error('Map focus failed');
const fallback=await browser.newPage({viewport:{width:1200,height:800}});
await fallback.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return type==='webgl'||type==='webgl2'?null:original.call(this,type,...args);};});
await fallback.goto('http://127.0.0.1:5174/');
await fallback.locator('.room-map summary').click();await fallback.getByRole('button',{name:'About ↗',exact:true}).click();
await fallback.locator('#board-view').waitFor({state:'visible'});
if(!await fallback.locator('.board-text').getByText('Valdez · Software engineer · Systems / apps',{exact:true}).isVisible())throw Error('No-WebGL board unreadable');
await fallback.locator('.board-exit').click();
if(errors.length)throw Error(errors.join('\n'));
console.log('Whole board, no dialog, back/focus, resize, Room Map, reduced motion and native fallback passed.');
await browser.close();
