import {chromium} from '@playwright/test';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1536,height:960}});
await page.goto('http://127.0.0.1:5174/',{waitUntil:'networkidle'});
if(await page.locator('#stage > header,#stage > nav,#stage > footer,.intro').count())throw Error('Traditional page chrome remains');
await page.locator('.room-map summary').click();await page.getByRole('button',{name:'Projects ↗',exact:true}).click();
await page.locator('#world-desktop').waitFor({state:'visible'});await page.waitForTimeout(200);
if(await page.evaluate(()=>__roomDebug.comicWorld.focusStrength)<.9)throw Error('PC panel convergence failed');
