if(!await page.locator('.room-map summary').evaluate(el=>el===document.activeElement))throw Error('Room Map focus was not restored');
await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(500);
const before=await page.evaluate(()=>__roomDebug.comicWorld.objects[0].group.position.toArray());
